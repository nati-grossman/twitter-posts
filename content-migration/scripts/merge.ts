/**
 * Deterministic merge of per-series outputs into content-migration/single-tweets.json,
 * plus src/data/seed/singleTweets.ts which the editor uses to show the single tweet.
 * Order follows the app: topic order in SEED_TOPICS, then series, then part.
 * Every source post appears exactly once; posts without an approved tweet have tweet = null.
 *
 *   npx tsx content-migration/scripts/merge.ts            include only status "ok"
 *   npx tsx content-migration/scripts/merge.ts --all      include any tweet that passed hard checks
 */
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { MERGED_PATH, ROOT, graphemeLength, loadAllOutputs, loadAllSources, loadManifest, weightedLength, writeJson, type OutputEntry } from './lib.ts'
import { SEED_TOPICS } from '../../src/data/seed/topics/index.ts'

const APP_TWEETS_PATH = join(ROOT, '..', 'src', 'data', 'seed', 'singleTweets.ts')
const includeUnreviewed = process.argv.includes('--all')
const manifest = loadManifest()
if (!manifest) throw new Error('No manifest.json. Run validate.ts first.')

const tweets = new Map<string, OutputEntry>()
for (const { entries } of loadAllOutputs()) {
  if (!Array.isArray(entries)) continue
  for (const e of entries as OutputEntry[]) if (!tweets.has(e.key)) tweets.set(e.key, e)
}

const topicOrder = new Map(SEED_TOPICS.map((t, i) => [t.id, i]))
const sources = loadAllSources().sort(
  (a, b) =>
    topicOrder.get(a.topicId)! - topicOrder.get(b.topicId)! ||
    a.seriesIndex - b.seriesIndex ||
    a.part - b.part,
)

const accepted = new Set(includeUnreviewed ? ['ok', 'needs_review'] : ['ok'])
const posts = sources.map((s) => {
  const m = manifest.entries[s.key]
  const out = tweets.get(s.key)
  const usable = m && accepted.has(m.status) && out && out.sourceHash === s.sourceHash
  const tweet = usable ? out.tweet : null
  return {
    id: s.key,
    topicId: s.topicId,
    topicName: s.topicName,
    seriesIndex: s.seriesIndex,
    seriesName: s.seriesName,
    part: s.part,
    title: s.title,
    subtitle: s.subtitle,
    postType: s.postType,
    tags: s.tags,
    originalText: s.sourceText,
    originalChars: s.sourceChars,
    tweet,
    chars: tweet ? graphemeLength(tweet) : null,
    weightedLength: tweet ? weightedLength(tweet) : null,
    status: m?.status ?? 'pending',
  }
})

// Lookup used by the app's editor: key = topicId \0 series name \0 part (same matching as the seed sync).
const appTweets: Record<string, string> = {}
for (const p of posts) {
  if (p.tweet) appTweets[`${p.topicId}\0${p.seriesName}\0${p.part}`] = p.tweet
}
writeFileSync(
  APP_TWEETS_PATH,
  '// Generated by content-migration/scripts/merge.ts — do not edit by hand.\n' +
    `export const SINGLE_TWEETS: Record<string, string> = ${JSON.stringify(appTweets, null, 2)}\n`,
  'utf8',
)

writeJson(MERGED_PATH, {
  version: 1,
  limit: manifest.limit,
  includes: [...accepted],
  total: posts.length,
  withTweet: posts.filter((p) => p.tweet).length,
  posts,
})
console.log(`Wrote ${posts.length} posts (${posts.filter((p) => p.tweet).length} with tweet) to ${MERGED_PATH}`)
